import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
const tokens=read('src/design-system/tokens.css');
const components=read('src/design-system/components.css');
const ui=read('src/components/ui/index.tsx');
const icons=read('src/design-system/icons.ts');
const wb=read('src/runtime/whiteboard-core.css');
const app=read('src/App.tsx');
const files=[...fs.readdirSync('src/views').map(n=>'src/views/'+n), 'src/App.tsx','src/components/Toast.tsx'];
let ok=0, total=0;
function check(name,pass){total++; if(!pass){console.error('FAIL '+name);process.exitCode=1}else{ok++;console.log('OK   '+name)}}
const v=String(pkg.version||'').split('.').map(Number); const atLeast1162=(v[0]>1)||(v[0]===1&&(v[1]>16||(v[1]===16&&v[2]>=2)));
check('baseline V1.16.2 preservada em versão >= 1.16.2',atLeast1162);
check('escala tipográfica v4 começa em 11px',tokens.includes('--bo-font-size-2xs:11px')&&!tokens.includes('--bo-font-size-2xs:10px'));
check('tokens de ícone e camadas',tokens.includes('--bo-icon-md:18px')&&tokens.includes('--bo-layer-dialog:1000'));
check('aliases semânticos do board',tokens.includes('--bo-board-canvas:')&&tokens.includes('--bo-board-focus:'));
check('aliases legados sem !important nos custom properties',!/--rt-[^;]+!important/.test(tokens));
check('facade único de ícones',icons.includes("export * from 'lucide-react'"));
check('produto não importa lucide diretamente',files.every(p=>!read(p).includes("from 'lucide-react'")));
check('biblioteca React ampliada',/function Chip/.test(ui)&&/function Field/.test(ui)&&/function Tabs/.test(ui)&&/function Skeleton/.test(ui));
check('página interna Design System',fs.existsSync('src/views/DesignSystemView.tsx')&&app.includes("design-system') === '1"));
check('Whiteboard sem paleta slate estrutural',!/#(?:64748b|e2e8f0|0f172a|f8fafc|94a3b8|334155|475569|cbd5e1|dbe3ee|3b82f6)\b/i.test(wb));
const important=(wb.match(/!important/g)||[]).length;
check('dívida !important reduzida para <= 300',important<=300);
const sizes=[...wb.matchAll(/font-size\s*:\s*([0-9.]+)px/g)].map(m=>Number(m[1]));
check('piso tipográfico do board preservado >= 11px',sizes.every(n=>n>=11));
check('componentes v4 possuem Chip Tooltip e DS page',components.includes('.bo-chip')&&components.includes('.bo-tooltip')&&components.includes('.bo-ds-page'));
check('body marca bo-v1162',read('src/main.tsx').includes("'bo-v1162'"));
console.log(`V1.16.2 Design System v4: ${ok}/${total} · !important=${important}`);
if(process.exitCode) process.exit(process.exitCode);
