#!/usr/bin/env python3
"""Needs + shared Entity Canvas browser regression: save, optional blocks, tags, deletion."""
import functools, json, threading
from pathlib import Path
from http.server import SimpleHTTPRequestHandler,ThreadingHTTPServer
from playwright.sync_api import sync_playwright,expect

ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'artifacts'/'entity-canvas-needs';OUT.mkdir(parents=True,exist_ok=True)
assert (ROOT/'dist'/'index.html').exists(),'dist is required'
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(SimpleHTTPRequestHandler,directory=str(ROOT/'dist')))
threading.Thread(target=server.serve_forever,daemon=True).start()
checks=[]
def check(label,pred):
 checks.append({'name':label,'ok':bool(pred)})
 if not pred: raise AssertionError(label)
 print('PASS '+label,flush=True)
try:
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True)
  page=browser.new_page(viewport={'width':1460,'height':900})
  page.goto(f'http://127.0.0.1:{server.server_port}',wait_until='domcontentloaded')
  page.get_by_role('button',name='Abrir workspace local sem conta').click()
  page.get_by_role('button',name='Novo projeto',exact=True).click()
  page.get_by_label('Nome do projeto',exact=True).fill('Needs Canvas QA')
  page.get_by_label('Serviço principal',exact=True).fill('Compra digital')
  page.get_by_role('button',name='Criar projeto',exact=True).click()
  page.locator('button[aria-label="Necessidades"]').first.click()
  library=page.locator('[data-needs-h72="library"]')
  expect(library).to_be_visible()
  library.locator('.bo-h71-toolbar').get_by_role('button',name='Criar necessidade').click()
  form=page.locator('form.bo-h71-create-modal')
  form.locator('input').first.fill('Calcular frete com previsibilidade')
  form.get_by_role('button',name='Criar e abrir').click()
  detail=page.locator('[data-needs-h72="detail"]')
  expect(detail).to_be_visible()
  canvas=detail.locator('[data-entity-canvas="1"]')
  check('Two primary blocks',canvas.locator('.bo-pain-canvas-card').count()==2)
  check('Three optional ghost blocks',canvas.locator('.bo-pain-canvas-ghost').count()==3)
  detail.get_by_role('textbox',name='Contexto',exact=True).fill('No checkout pelo telefone celular.')
  detail.get_by_role('textbox',name='Resultado desejado',exact=True).fill('Conseguir avaliar o custo total antes do pagamento.')
  canvas.get_by_role('button',name='Descrição',exact=True).click()
  detail.get_by_role('textbox',name='Descrição',exact=True).fill('Pessoas precisam planejar os custos de entrega.')
  detail.get_by_role('textbox',name='Adicionar tag').fill('Checkout')
  detail.get_by_role('textbox',name='Adicionar tag').press('Enter')
  check('Tag chip rendered',detail.locator('.bo-entity-tag').filter(has_text='Checkout').count()==1)
  canvas.get_by_role('button',name='Adicionar campo').click()
  canvas.get_by_role('button',name='Texto',exact=True).click()
  canvas.get_by_role('textbox',name='Texto',exact=True).fill('Campo extra com informação persistida.')
  canvas.get_by_role('button',name='Alternativa atual',exact=True).click()
  canvas.get_by_role('textbox',name='Alternativa atual',exact=True).fill('Consultar tabela externa.')
  card=canvas.locator('.bo-pain-canvas-card').filter(has=canvas.get_by_role('textbox',name='Alternativa atual',exact=True))
  card.get_by_role('button',name='Opções de Alternativa atual').click()
  card.get_by_role('button',name='Ocultar bloco (preserva conteúdo)').click()
  check('Hidden block indicates preserved text','Conteúdo preservado' in canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Alternativa atual').inner_text())
  detail.screenshot(path=str(OUT/'needs-canvas.png'),full_page=True)
  detail.locator('.bo-pain-back').click()
  expect(library).to_be_visible()
  library.locator('.bo-h72-need-name').first.click()
  expect(detail).to_be_visible()
  check('Primary value persisted',detail.get_by_role('textbox',name='Contexto',exact=True).input_value()=='No checkout pelo telefone celular.')
  check('Custom field persisted',canvas.get_by_role('textbox',name='Texto',exact=True).input_value()=='Campo extra com informação persistida.')
  check('Tag persisted after reopening',detail.locator('.bo-entity-tag').filter(has_text='Checkout').count()==1)
  canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Alternativa atual').click()
  check('Previously hidden data recovered',canvas.get_by_role('textbox',name='Alternativa atual',exact=True).input_value()=='Consultar tabela externa.')
  detail.get_by_role('button',name='Excluir',exact=True).first.click()
  dialog=page.get_by_role('alertdialog',name='Excluir necessidade')
  expect(dialog).to_be_visible()
  dialog.get_by_role('button',name='Cancelar').click()
  check('Cancel deletion keeps record',detail.is_visible())
  (OUT/'result.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2),encoding='utf-8')
  browser.close()
finally: server.shutdown()
