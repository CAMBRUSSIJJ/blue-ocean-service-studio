import { readFileSync, existsSync } from 'node:fs';
const read = p => readFileSync(p, 'utf8');
const checks=[]; const check=(name,ok)=>{checks.push([name,Boolean(ok)]);console.log(`${ok?'OK  ':'FAIL'} ${name}`)};
const pkg=JSON.parse(read('package.json'));
const css=read('src/runtime/precision-studio-shell.css');
const tokens=read('src/design-system/tokens.css').toLowerCase();
const js=read('src/runtime/precision-studio-shell.js');
const app=read('src/App.tsx');
const index=read('index.html');
const prep=read('scripts/prepare-assets.mjs');
check('baseline Precision Studio preservada em versão >= 1.15.3',(()=>{const [a,b,c]=pkg.version.split('.').map(Number);return a>1||(a===1&&(b>15||(b===15&&c>=3)))})());
check('runtime Precision Studio existe',existsSync('src/runtime/precision-studio-shell.js')&&js.includes("const VERSION='__APP_VERSION__';"));
check('CSS Precision Studio existe',existsSync('src/runtime/precision-studio-shell.css')&&css.includes('Precision Studio Shell'));
check('sidebar compacta 216/60',tokens.includes('--bo-sidebar-w:216px')&&css.includes('width:60px!important'));
check('header compacto 48px',tokens.includes('--bo-header-h:48px')&&css.includes('header.rt182-host-header'));
check('canvas neutro e superfícies claras',tokens.includes('--bo-color-canvas:#f7f8fa')&&tokens.includes('--bo-color-surface:#ffffff'));
check('Home reduz cardificação',css.includes('.bo114-home-hero')&&css.includes('background:transparent!important')&&css.includes('.bo114-home-grid-kpis'));
check('collapse persistente e atalho',js.includes('blue-ocean:precision-studio:sidebar-collapsed')&&js.includes("event.key==='\\\\'"));
check('Inspector Universal disponível',js.includes('openInspector')&&css.includes('.bo1152-inspector'));
check('toolbar contextual disponível',js.includes('showToolbar')&&css.includes('.bo1152-floating-toolbar'));
check('API registrada',js.includes("register?.('precisionStudio'"));
check('hooks nativos no App',app.includes('data-bo-precision-sidebar-native')&&app.includes('data-bo-precision-header-native')&&app.includes('data-bo-precision-workspace-native'));
check('assets no pipeline',prep.includes('v1153-precision-studio.js')&&prep.includes('v1153-precision-studio.css'));
check('assets no bootstrap',index.includes('v1153-precision-studio.css')&&index.includes('v1153-precision-studio.js'));
check('CSS responsivo',css.includes('@media(max-width:1120px)')&&css.includes('@media(max-width:720px)'));
check('sem MutationObserver',!js.includes('MutationObserver'));
check('sem armazenamento paralelo do Service Graph',!js.includes('realtalent.service.graph')&&!js.includes('graph='));
const failed=checks.filter(([,ok])=>!ok).length;
console.log(`\nV1.15.3 Precision Studio Shell: ${checks.length-failed}/${checks.length}`);
if(failed) process.exit(1);
