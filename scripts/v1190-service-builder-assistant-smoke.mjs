import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const core=read('src/runtime/whiteboard-core.js');
const css=read('src/runtime/service-builder-assistant.css');
const style=read('src/style.css');
const home=read('src/views/WorkspaceHome.tsx');
const whiteboards=read('src/views/WhiteboardsView.tsx');
const guidance=read('src/runtime/guidance-engine.js');
const pkg=JSON.parse(read('package.json'));
const checks=[];
const ok=(name,cond)=>checks.push([name,!!cond]);

const atLeast=(v,a,b,c)=>{const [x=0,y=0,z=0]=String(v).split('.').map(Number);return x>a||(x===a&&(y>b||(y===b&&z>=c)))};
ok('package 1.19.0 ou superior',atLeast(pkg.version,1,19,0));
ok('assistant smoke registered',pkg.scripts?.['assistant:smoke']?.includes('v1190-service-builder-assistant-smoke.mjs'));
ok('assistant css imported before tailwind',style.indexOf("service-builder-assistant.css")>0 && style.indexOf("service-builder-assistant.css")<style.indexOf('@tailwind base'));
ok('assistant css panel',css.includes('.bo1190-assistant-panel'));
ok('assistant css tabs',css.includes('.bo1190-assistant-tabs'));
ok('assistant css ask',css.includes('.bo1190-assistant-ask'));
ok('assistant state per board',core.includes('meta.serviceBuilderAssistant.boards'));
ok('assistant has create mode',core.includes("mode:'create'"));
ok('assistant four modes',core.includes("['create','understand','review','improve']"));
ok('assistant progress has objective',core.includes("key:'objective'"));
ok('assistant progress has evidence',core.includes("key:'evidence'"));
ok('assistant progress has review',core.includes("key:'review'"));
ok('assistant objective start boundary',core.includes('startBoundary'));
ok('assistant objective end boundary',core.includes('endBoundary'));
ok('assistant deterministic question',core.includes('function assistantAnswer(question)'));
ok('assistant question help no AI requirement',core.includes("q.includes('diferença')") && core.includes("q.includes('terminei')"));
ok('assistant create service basics',core.includes('function assistantEditServiceBasics()'));
ok('assistant create persona',core.includes('function assistantEditPersona()'));
ok('assistant create journey',core.includes('function assistantCreateJourney()'));
ok('assistant add stage',core.includes('function assistantAddStage()'));
ok('assistant journey stays on board',!core.match(/function assistantCreateJourney\(\)[\s\S]{0,2200}openJourneyFromHome/));
ok('assistant stage creates smart instance',core.includes("addSmart('stage',id,point)")||core.includes("assistantEnsureSmartItem('stage',id)"));
ok('assistant persona creates smart instance',core.includes("addSmart('persona',id")||core.includes("assistantEnsureSmartItem('persona',id)"));
ok('assistant stageflow preserves free view',core.includes("if(options.fromAssistant)return addBlueprintEntity(key,stageId,null,options)"));
ok('assistant returns from stage flow',core.includes('← Voltar ao assistente'));
ok('assistant API registered',core.includes("runtime.register('serviceBuilderAssistant'"));
ok('assistant start requires free board',core.includes("board().viewKind!=='free'"));
ok('blank board remains empty',core.includes("createBoard(clean,{viewKind:'free',layoutMode:'free',items:{},edges:{}})"));
ok('empty state offers assistant or Discovery-first service builder',core.includes('Montar com assistente')||core.includes("btn('Montar serviço'"));
ok('empty state preserves free exploration and points structured design to Blueprints',whiteboards.includes('Ir para Blueprints')&&whiteboards.includes('livre'));
ok('home guided creates blank board first',home.includes("core?.createBlank") && home.includes("serviceBuilderAssistant"));
ok('home guided uses service named board',home.includes("`${graph.service.name || 'Serviço'} · construção`"));
ok('whiteboard library no longer exposes structured guided build',!whiteboards.includes('✦ Montar com assistente')&&!whiteboards.includes('✦ Montar serviço')&&whiteboards.includes('Ir para Blueprints'));
ok('whiteboard library creates only free blank boards',whiteboards.includes('createBlank')&&!whiteboards.includes('createGuided'));
ok('guidance objective mapping',guidance.includes("objective:'service'"));
ok('guidance evidence mapping',guidance.includes("evidence:'evidence'"));
ok('assistant does not start automatically on blank board',core.includes("if(!state.active){if(!Object.keys(board().items||{}).length)"));
ok('assistant pause keeps session',core.includes('function pauseServiceBuilderAssistant()'));
ok('assistant persists question',core.includes('state.lastQuestion'));
ok('assistant persists answer',core.includes('state.lastAnswer'));
ok('assistant review does not invent content',core.includes('ele não inventa conteúdo'));
ok('assistant final review explicit',core.includes('Concluir primeira versão'));
ok('assistant current step navigable',core.includes('state.currentStep=step.key'));
ok('assistant mode understand',core.includes('function renderAssistantUnderstandMode'));
ok('assistant mode review',core.includes('function renderAssistantReviewMode'));
ok('assistant mode improve',core.includes('function renderAssistantImproveMode'));
ok('assistant improvement problem action',core.includes("Adicionar problema"));
ok('assistant improvement opportunity action',core.includes("Criar oportunidade"));
ok('assistant improvement metric action',core.includes("Definir métrica"));
ok('assistant panel only on free layout',core.includes("(pref().layoutMode||'free')!=='free'"));
ok('assistant mobile css',css.includes('@media(max-width:900px)'));

const failed=checks.filter(([,v])=>!v);
for(const [name,value] of checks) console.log(`${value?'OK  ':'FAIL'} ${name}`);
console.log(`\nService Builder Assistant: ${checks.length-failed.length}/${checks.length}`);
if(failed.length) process.exit(1);
