#!/usr/bin/env python3
"""End-to-end acceptance of card metadata, filters, bulk edits and saved views."""
import functools, json, os, shutil, threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'artifacts/journey-card-tools'
OUT.mkdir(parents=True, exist_ok=True)
checks, errors = [], []

class Quiet(SimpleHTTPRequestHandler):
    def log_message(self, *_): pass
    def copyfile(self, source, output):
        try: super().copyfile(source, output)
        except (BrokenPipeError, ConnectionResetError): pass

server = ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=str(ROOT / 'dist')))
threading.Thread(target=server.serve_forever, daemon=True).start()

def check(name, value):
    assert value, name
    checks.append(name)
    print('PASS ' + name, flush=True)

def graph(page): return page.evaluate("()=>window.BlueOceanRuntime.api('dataBridge').get()")
def saved(f): expect(f.locator('[data-save-status]')).to_have_text('Salvo neste navegador')
def stage(f, title):
    f.get_by_role('button', name='Adicionar etapa', exact=True).click()
    f.get_by_role('textbox', name='Nome da nova etapa', exact=True).fill(title)
    f.get_by_role('button', name='Adicionar etapa ao mapa', exact=True).click()
    saved(f)
def inline(f, key, text):
    f.locator(f'[data-cell="{key}"]>.content-add').click()
    f.get_by_role('button', name='Adicionar Texto', exact=True).click()
    field = f.locator(f'[data-cell="{key}"] [data-ed="c"]').last
    field.fill(text); field.press('Tab'); saved(f)
def select_mode(f):
    button = f.get_by_role('button', name='Selecionar cartões', exact=True)
    if button.count(): button.click()

def classification(f, index):
    block = f.locator('.content-block').nth(index)
    block.get_by_label('Ações da nota', exact=True).click()
    block.get_by_role('button', name='Classificar cartão', exact=True).click()
    return f.locator('#card-classification-dialog')
def filters(f, persona='', tag='', common=True, query=''):
    form = f.locator('#card-filter-form')
    form.get_by_label('Buscar cartões', exact=True).fill(query)
    form.get_by_label('Persona dos cartões', exact=True).select_option(persona)
    form.get_by_label('Tag', exact=True).select_option(tag)
    form.get_by_label('Incluir sem Persona', exact=True).set_checked(common)
    form.get_by_role('button', name='Aplicar filtros', exact=True).click(); saved(f)
def audit(page, f, name):
    frame = page.locator('.bo-blueprint-reference-frame').element_handle().content_frame()
    frame.add_script_tag(content=(ROOT / 'node_modules/axe-core/axe.min.js').read_text())
    violations = frame.evaluate("async()=>{const r=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))}")
    (OUT / (name + '-axe.json')).write_text(json.dumps(violations, indent=2))
    check('Accessibility: ' + name, not violations)

try:
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True, executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'), args=['--no-sandbox', '--disable-dev-shm-usage'])
        page = browser.new_page(viewport={'width': 1440, 'height': 1000}, accept_downloads=True)
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.add_locator_handler(page.locator('.rt155-recovery-notice.show'), lambda n: n.locator('i').click())
        page.goto(f'http://127.0.0.1:{server.server_port}', wait_until='networkidle')
        page.get_by_role('button', name='Abrir workspace local sem conta').click()
        page.get_by_role('button', name='Novo projeto', exact=True).click()
        page.get_by_label('Nome do projeto', exact=True).fill('QA Cartões por Persona')
        page.get_by_label('Serviço principal', exact=True).fill('Atendimento')
        page.get_by_role('button', name='Criar projeto', exact=True).click()
        page.locator('.bo-h724-journey-pane').get_by_role('button', name='Criar Jornada', exact=True).click()
        page.get_by_role('button', name='Em branco').first.click()
        f = page.frame_locator('.bo-blueprint-reference-frame')
        expect(f.get_by_role('button', name='Adicionar etapa', exact=True)).to_be_visible()
        stage(f, 'Descobrir'); stage(f, 'Usar')
        page.evaluate("""()=>window.BlueOceanRuntime.api('dataBridge').transact(g=>{const now=new Date().toISOString();for(const [kind,id,title] of [['persona','qa-a','Marina'],['persona','qa-b','João'],['channel','qa-channel','WhatsApp']]){g.entities[kind]||={};g.entities[kind][id]={id,type:kind,serviceId:g.service.id,title,createdAt:now,updatedAt:now}}return g},'Dados fictícios de aceitação')""")
        f.get_by_role('button', name='+ Adicionar faixa', exact=True).click()
        f.get_by_role('button', name='Faixa personalizada →', exact=True).click()
        f.get_by_role('searchbox', name='Buscar tipo de conteúdo', exact=True).fill('texto')
        f.get_by_role('searchbox', name='Buscar tipo de conteúdo', exact=True).press('Enter')
        lane = f.locator('.r[data-row^="x"]').last.get_attribute('data-row')
        key = lane + '|0'
        inline(f, key, 'Somente Marina'); inline(f, key, 'Somente João'); inline(f, key, 'Compartilhado')
        state = graph(page); jid = next(iter(state['journeys'])); sid = state['journeys'][jid]['stageIds'][0]
        def notes(): return graph(page)['journeys'][jid]['matrixContent']['cells'][sid][lane]

        dialog = classification(f, 0)
        dialog.get_by_label('Marina', exact=True).check()
        dialog.get_by_label('Tags, separadas por vírgulas', exact=True).fill('VIP, Pesquisa')
        dialog.get_by_label('Destaque do cartão', exact=True).select_option('blue')
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Single-card classification reaches the canonical project', notes()[0]['personaIds'] == ['qa-a'] and notes()[0]['tags'] == ['VIP', 'Pesquisa'])
        dialog = classification(f, 1); dialog.get_by_label('João', exact=True).check()
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        filters(f, persona='qa-a', common=False)
        expect(f.locator('.content-block')).to_have_count(1)
        check('Persona filter hides other cards without changing stored data', len(notes()) == 3 and f.locator('.content-block [data-ed="c"]').inner_text() == 'Somente Marina')
        filters(f, persona='qa-b', common=False)
        dialog = classification(f, 0)
        dialog.get_by_label('Tags, separadas por vírgulas', exact=True).fill('Retorno')
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Editing a filtered card keeps its original identity and index', notes()[1]['tags'] == ['Retorno'] and notes()[0]['tags'] == ['VIP', 'Pesquisa'])
        filters(f, persona='qa-a', common=True)
        expect(f.locator('.content-block')).to_have_count(2)
        check('Unassigned cards are optionally included in a Persona view', len(notes()) == 3)
        f.get_by_role('button', name='Limpar filtros', exact=True).click(); saved(f)
        f.locator(f'[data-cell="{key}"]>.content-add').click()
        f.get_by_role('button', name='Adicionar Canal', exact=True).click()
        d = f.locator('#content-editor'); d.get_by_label('Registro do serviço', exact=True).select_option('qa-channel')
        d.get_by_role('button', name='Salvar elemento', exact=True).click(); saved(f)
        before_bulk = notes()
        f.get_by_role('button', name='Selecionar cartões', exact=True).click()
        select_mode(f)
        f.get_by_role('button', name='Selecionar visíveis', exact=True).click()
        f.get_by_role('button', name='Classificar seleção', exact=True).click()
        dialog = f.locator('#card-classification-dialog')
        dialog.get_by_label('Tags, separadas por vírgulas', exact=True).fill('Equipe')
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Bulk tags work across text and linked cards', len(notes()) == 4 and all('Equipe' in n['tags'] for n in notes()) and notes()[-1]['referenceId'] == 'qa-channel')
        f.get_by_role('button', name='Desfazer', exact=True).click(); saved(f)
        check('One undo restores the whole bulk operation', notes() == before_bulk)
        f.get_by_role('button', name='Refazer', exact=True).click(); saved(f)
        check('Redo restores the bulk classification', all('Equipe' in n['tags'] for n in notes()))
        select_mode(f)
        f.get_by_role('button', name='Selecionar visíveis', exact=True).click()
        f.get_by_role('button', name='Classificar seleção', exact=True).click()
        dialog = f.locator('#card-classification-dialog')
        dialog.get_by_label('Alteração', exact=True).select_option('persona-add')
        dialog.get_by_label('Marina', exact=True).check()
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Bulk Persona assignment preserves other Personas', all('qa-a' in n['personaIds'] for n in notes()) and 'qa-b' in notes()[1]['personaIds'])
        f.get_by_role('button', name='Limpar seleção', exact=True).click()
        for index in [1, 2, 3]:
            f.locator('.content-block').nth(index).locator('[data-card-select]').check()
        f.get_by_role('button', name='Classificar seleção', exact=True).click()
        dialog = f.locator('#card-classification-dialog')
        dialog.get_by_label('Alteração', exact=True).select_option('persona-remove')
        dialog.get_by_label('Marina', exact=True).check()
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Hand-picked bulk removal does not change an unselected card', notes()[0]['personaIds'] == ['qa-a'] and notes()[1]['personaIds'] == ['qa-b'] and notes()[2]['personaIds'] == [])
        f.get_by_role('button', name='Selecionar visíveis', exact=True).click()
        f.get_by_role('button', name='Classificar seleção', exact=True).click()
        dialog = f.locator('#card-classification-dialog')
        dialog.get_by_label('Alteração', exact=True).select_option('tone')
        dialog.get_by_label('Destaque do cartão', exact=True).select_option('violet')
        dialog.get_by_role('button', name='Salvar classificação', exact=True).click(); saved(f)
        check('Bulk highlighting works for mixed card types', all(n['tone'] == 'violet' for n in notes()))
        select_mode(f)
        f.get_by_role('button', name='Selecionar visíveis', exact=True).click()
        f.get_by_role('button', name='Excluir seleção', exact=True).click()
        f.locator('#card-classification-dialog').get_by_role('button', name='Cancelar', exact=True).click()
        check('Cancelling bulk deletion leaves all cards intact', len(notes()) == 4)
        f.get_by_role('button', name='Excluir seleção', exact=True).click()
        f.get_by_role('button', name='Confirmar exclusão', exact=True).click(); saved(f)
        check('Bulk deletion removes representations and retains the service record', not notes() and 'qa-channel' in graph(page)['entities']['channel'])
        f.get_by_role('button', name='Desfazer', exact=True).click(); saved(f)
        check('Undo restores deleted cards and their metadata', len(notes()) == 4 and all('Equipe' in n['tags'] for n in notes()))
        finish = f.get_by_role('button', name='Concluir seleção', exact=True)
        if finish.count(): finish.click()
        filters(f, persona='qa-a', tag='VIP', common=False, query='marina')
        f.get_by_role('button', name='Visualizações', exact=True).click()
        d = f.locator('#journey-views-dialog'); d.get_by_label('Nome da visualização', exact=True).fill('Marina VIP')
        d.get_by_role('button', name='Salvar visualização atual', exact=True).click()
        expect(d.get_by_role('button', name='Aplicar visualização Marina VIP', exact=True)).to_be_enabled()
        d.get_by_role('button', name='Voltar ao mapa', exact=True).click()
        f.get_by_role('button', name='Limpar filtros', exact=True).click(); saved(f)
        expect(f.locator('.content-block')).to_have_count(4)
        f.get_by_role('button', name='Visualizações', exact=True).click()
        f.get_by_role('button', name='Aplicar visualização Marina VIP', exact=True).click(); saved(f)
        expect(f.locator('.content-block')).to_have_count(1)
        check('Saved views restore combined filters on the same current data', len(notes()) == 4 and graph(page)['journeys'][jid]['matrixView']['cardFilters']['tag'] == 'VIP')
        f.get_by_role('button', name='Visualizações', exact=True).click()
        f.get_by_role('button', name='Apresentar visualização atual', exact=True).click()
        body = f.locator('.executive-report').inner_text()
        check('Filtered presentation includes matching cards only', 'Somente Marina' in body and 'Somente João' not in body and 'Compartilhado' not in body)
        with page.expect_download() as download:
            f.get_by_role('button', name='Baixar resumo HTML', exact=True).click()
        exported = Path(download.value.path()).read_text()
        check('Downloaded HTML uses the same card filters', 'Somente Marina' in exported and 'Somente João' not in exported and 'Compartilhado' not in exported)
        f.get_by_role('button', name='Voltar ao mapa', exact=True).click()
        f.get_by_role('button', name='Voltar para Jornadas', exact=True).click(); page.reload(wait_until='networkidle')
        page.get_by_role('button', name='Abrir Jornadas', exact=True).click()
        page.get_by_role('button', name='Abrir Jornada', exact=True).first.click(); saved(f)
        expect(f.locator('.content-block')).to_have_count(1)
        check('Reload preserves classifications, stable identities and active filters', len(notes()) == 4 and notes()[0]['personaIds'] == ['qa-a'] and notes()[-1]['referenceId'] == 'qa-channel')
        for width in [1440, 834, 390]:
            page.set_viewport_size({'width': width, 'height': 1000})
            audit(page, f, 'map-' + str(width))
            page.screenshot(path=str(OUT / f'map-{width}.png'), animations='disabled')
            dialog = classification(f, 0)
            box = dialog.bounding_box()
            check(f'Classification fits inside {width}px', box['x'] >= 0 and box['x'] + box['width'] <= width and box['height'] <= 1000)
            audit(page, f, 'classification-' + str(width))
            page.screenshot(path=str(OUT / f'classification-{width}.png'), animations='disabled')
            dialog.get_by_role('button', name='Cancelar', exact=True).click()
        mobile_context = browser.new_context(viewport={'width': 390, 'height': 844}, has_touch=True, is_mobile=True, storage_state=page.context.storage_state())
        mobile = mobile_context.new_page(); mobile.on('pageerror', lambda e: errors.append(str(e)))
        mobile.add_locator_handler(mobile.locator('.rt155-recovery-notice.show'), lambda n: n.locator('i').click())
        mobile.goto(f'http://127.0.0.1:{server.server_port}', wait_until='networkidle')
        mobile.get_by_role('button', name='Abrir workspace local sem conta').click()
        mobile.get_by_role('button', name='Abrir navegação', exact=True).click()
        mobile.get_by_role('button', name='Abrir Jornadas', exact=True).click()
        mobile.get_by_role('button', name='Abrir Jornada', exact=True).first.click()
        mf = mobile.frame_locator('.bo-blueprint-reference-frame'); saved(mf)
        mf.get_by_role('button', name='Selecionar cartões', exact=True).tap()
        mf.get_by_label('Selecionar cartão Somente Marina', exact=True).tap()
        mf.get_by_role('button', name='Classificar seleção', exact=True).tap()
        md = mf.locator('#card-classification-dialog')
        md.get_by_label('Tags, separadas por vírgulas', exact=True).fill('Toque')
        md.get_by_role('button', name='Salvar classificação', exact=True).tap(); saved(mf)
        check('Touch selection and bulk editing preserve the filtered card identity', 'Toque' in graph(mobile)['journeys'][jid]['matrixContent']['cells'][sid][lane][0]['tags'])
        audit(mobile, mf, 'touch-bulk')
        mobile_context.close()
        check('No uncaught browser errors', not errors)
        (OUT / 'results.json').write_text(json.dumps(checks, ensure_ascii=False, indent=2))
        browser.close()
except Exception:
    print('Browser errors:', errors, flush=True)
    raise
finally:
    server.shutdown(); server.server_close()
