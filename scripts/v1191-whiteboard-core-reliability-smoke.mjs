import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const core=read('src/runtime/whiteboard-core.js');
const p2=read('qa/whiteboard-sim/phase2.cjs');
const p4=read('qa/whiteboard-sim/phase4.cjs');
const p6=read('qa/whiteboard-sim/phase6.cjs');
const p7=read('qa/whiteboard-sim/phase7.cjs');
const runAll=read('qa/whiteboard-sim/run-all.sh');
const pkg=JSON.parse(read('package.json'));
const checks=[];
const ok=(name,cond)=>checks.push([name,!!cond]);
const atLeast=(v,a,b,c)=>{const [x=0,y=0,z=0]=String(v).split('.').map(Number);return x>a||(x===a&&(y>b||(y===b&&z>=c)))};

ok('package V1.19.1 ou superior',atLeast(pkg.version,1,19,1));
ok('gate reliability registrado',pkg.scripts?.['reliability:smoke']?.includes('v1191-whiteboard-core-reliability-smoke.mjs'));
ok('qa inclui reliability gate',String(pkg.scripts?.qa||'').includes('reliability:smoke'));
ok('canvas usa mínimos, não tamanho físico fixo',core.includes('MIN_BOARD_W = 5200')&&core.includes('MIN_BOARD_H = 3200')&&!core.includes('const BOARD_W=5200')&&!core.includes('const BOARD_W = 5200'));
ok('world size é derivado de conteúdo',core.includes('function boardWorldSize()'));
ok('viewport usa world dinâmico',core.includes('world=boardWorldSize()'));
ok('overlay canvas recebe world width',core.includes("canvas.style.width=world.width+'px'"));
ok('placement engine existe',core.includes('function findOpenPlacement('));
ok('placement evita colisão',core.includes('rectanglesOverlap(r,it)'));
ok('addFree usa placement quando ponto não é explícito',core.includes('p=point?base:findOpenPlacement(base,d)'));
ok('edição de texto possui modo incremental',core.includes('liveTextEditing=true'));
ok('save desliga full render durante texto',core.includes('if(liveTextEditing)render=false'));
ok('texto não gera snapshot por tecla',core.includes('!restoringEdit&&!liveTextEditing'));
ok('texto consolida histórico no blur',core.includes("i.onblur=()=>{if(!changed)return")&&core.includes("label:'Editar texto'"));
ok('item selecionado atualiza DOM incrementalmente',core.includes('function refreshSelectedItemDom()'));
ok('drag atualiza geometria sem renderAll por pointermove',core.includes('function updateItemGeometryDom(ids)'));
ok('pointer drag usa addEventListener',core.includes("addEventListener('pointerdown'"));
ok('shortcut guard detecta controles interativos',core.includes('function isUiControlTarget('));
ok('shortcut guard detecta contenteditable',core.includes('target?.isContentEditable')&&core.includes('[contenteditable]'));
ok('atalho global ignora controles UI',core.includes('if(isTypingTarget(e.target))')&&core.includes('if(isUiControlTarget(e.target))'));
ok('itens possuem tabindex',core.includes('el.tabIndex=0'));
ok('itens possuem role button',core.includes("el.setAttribute('role','button')"));
ok('itens possuem aria-label',core.includes("el.setAttribute('aria-label'"));
ok('toast possui aria-live',core.includes("setAttribute('aria-live','polite')"));
ok('toast possui role status',core.includes("setAttribute('role','status')"));
ok('navegação livre fecha sem reload',core.includes('function closeToWhiteboards(){close(false)'));
ok('navegação dispara whiteboards',core.includes("new CustomEvent('rt-navigation',{detail:'whiteboards'})"));
ok('rascunho de conflito é persistido',core.includes('function preserveConflictDraft('));
ok('API expõe conflictDraft',core.includes('conflictDraft:()=>clone(conflictDraft())'));
ok('conflito informa preservação',core.includes('rascunho de conflito'));
ok('primeiro quadro sincroniza serviço persistido',core.includes('refreshGraphFromStorageIfInitialized()'));
ok('assistant expõe setMode compatível',core.includes('setMode:assistantSetMode'));
ok('F2 mede foco/cursor',p2.includes('preserva foco/cursor'));
ok('F2 mede shortcut em botão',p2.includes('Atalho de uma letra dispara com foco em botão'));
ok('F4 verifica conflict draft',p4.includes('conflictDraft'));
ok('F4 verifica canvas cobrindo objeto distante',p4.includes('coversFar')&&p4.includes('x = 7000'));
ok('F6 template não depende de igualdade textual exata',p6.includes("includes('template')"));
ok('F6 ainda mede Smart Layout sobre colisão explícita',p6.includes("{ x: 600, y: 336 }"));
ok('F7 chama API setMode pública',p7.includes('assistant.setMode'));
ok('run-all usa pipefail',runAll.includes('set -euo pipefail'));
ok('run-all captura crash por fase',runAll.includes('crash-$p.txt'));
ok('run-all falha se houve crash',runAll.includes('if [[ "$crashed" -ne 0 ]]'));

const failed=checks.filter(([,v])=>!v);
for(const [name,value] of checks) console.log(`${value?'OK  ':'FAIL'} ${name}`);
console.log(`\nWhiteboard Core Reliability: ${checks.length-failed.length}/${checks.length}`);
if(failed.length) process.exit(1);
