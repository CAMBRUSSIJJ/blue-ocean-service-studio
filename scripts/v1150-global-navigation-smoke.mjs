import { readFileSync, existsSync } from 'node:fs';
const read = p => readFileSync(p, 'utf8');
const checks=[]; const check=(name,ok)=>{checks.push([name,!!ok]);console.log(`${ok?'OK  ':'FAIL'} ${name}`)};
const pkg=JSON.parse(read('package.json'));
const app=read('src/App.tsx');
const controller=read('src/state/useStudioController.ts');
const action=read('src/views/ActionPlanView.tsx');
const nav=read('src/runtime/global-navigation.js');
const css=read('src/runtime/global-navigation.css');
const index=read('index.html');
const prep=read('scripts/prepare-assets.mjs');
const research=read('src/runtime/research-workspace.js');
const intelligence=read('src/runtime/service-intelligence.js');
const benefits=read('src/runtime/benefits-realization.js');
check('versão >= 1.15.0',(()=>{const [a,b]=pkg.version.split('.').map(Number);return a>1||(a===1&&b>=15)})());
check('runtime Global Navigation existe',existsSync('src/runtime/global-navigation.js')&&/runtime\.register\('globalNavigation'/.test(nav));
check('busca indexa o Service Graph', ['journeys','stages','touchpoints','problems','opportunities','tasks','entities','research'].every(k=>nav.includes(`g.${k}`)||nav.includes(`g['${k}']`)));
check('Blueprints entram no índice',nav.includes("runtime.api('blueprintHome')")&&nav.includes("item('blueprint'"));
check('atalho Ctrl/Cmd K e /',/key\.toLowerCase\(\)==='k'/.test(nav)&&/e\.key==='\/'/.test(nav));
check('teclado de resultados',nav.includes("e.key==='ArrowDown'")&&nav.includes("e.key==='ArrowUp'")&&nav.includes("e.key==='Enter'"));
check('trigger nativo no header',/data-bo-global-search-native/.test(app)&&/globalNavigation/.test(app));
check('foco contextual de etapa',controller.includes('bo-global-object-focus')&&controller.includes('setSelectedStageIds'));
check('resultado de tarefa abre editor',action.includes('bo-global-object-focus')&&action.includes("detail.kind==='task'"));
check('Pesquisa possui deep-link',research.includes('openSource:id')&&research.includes('openEntity:(kind,id)'));
check('Inteligência possui deep-link',intelligence.includes('openMetric:id')&&intelligence.includes('openOpportunity:id'));
check('Benefícios possui deep-link',benefits.includes('openBenefit:id'));
check('asset V1.15 no pipeline',prep.includes('v1150-global-navigation.js')&&prep.includes('v1150-global-navigation.css'));
check('asset carregado antes do React',index.indexOf('v1150-global-navigation.js')>0&&index.indexOf('v1150-global-navigation.js')<index.indexOf('/src/main.tsx'));
check('CSS responsivo e dialog acessível',css.includes('@media(max-width:640px)')&&nav.includes('role="dialog"')&&nav.includes('role="listbox"'));
check('sem polling por MutationObserver',!nav.includes('MutationObserver'));
check('sem armazenamento paralelo de dados',!nav.includes('setItem(GRAPH')&&!nav.includes('realtalent.service.graph'));
const failed=checks.filter(([,ok])=>!ok).length;
console.log(`\nV1.15.0 Global Navigation: ${checks.length-failed}/${checks.length}`);
if(failed)process.exit(1);
