#!/usr/bin/env python3
"""Problem Entity Canvas regression: direct draft, autosave, custom fields and validation guard."""
import functools,json,threading
from pathlib import Path
from http.server import SimpleHTTPRequestHandler,ThreadingHTTPServer
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'artifacts'/'entity-canvas-problems';OUT.mkdir(parents=True,exist_ok=True)
assert (ROOT/'dist'/'index.html').exists()
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(SimpleHTTPRequestHandler,directory=str(ROOT/'dist')))
threading.Thread(target=server.serve_forever,daemon=True).start()
checks=[]
def check(name,ok):
 checks.append({'name':name,'pass':bool(ok)})
 if not ok:raise AssertionError(name)
 print('PASS '+name,flush=True)
try:
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True)
  page=browser.new_page(viewport={'width':1440,'height':920})
  page.goto(f'http://127.0.0.1:{server.server_port}',wait_until='domcontentloaded')
  page.get_by_role('button',name='Abrir workspace local sem conta').click()
  page.get_by_role('button',name='Novo projeto',exact=True).click()
  page.get_by_label('Nome do projeto',exact=True).fill('Problemas Canvas QA')
  page.get_by_label('Serviço principal',exact=True).fill('Compra de serviços')
  page.get_by_role('button',name='Criar projeto',exact=True).click()
  page.locator('button[aria-label="Problemas"]').first.click()
  library=page.locator('[data-problems-h76="library"]');expect(library).to_be_visible()
  library.locator('.bo-h71-toolbar').get_by_role('button',name='Criar problema').click()
  dlg=page.get_by_role('dialog',name='Criar problema');expect(dlg).to_be_visible()
  dlg.get_by_role('textbox',name='Enunciado do problema').fill('Clientes abandonam o cálculo do frete')
  dlg.get_by_role('button',name='Criar e abrir').click()
  detail=page.locator('[data-problems-h76="detail"]');expect(detail).to_be_visible()
  check('Draft status is visible',detail.get_by_text('PROBLEMA EM INVESTIGAÇÃO').count()>0)
  canvas=detail.locator('[data-entity-canvas="1"]')
  check('Three primary blocks',canvas.locator('.bo-pain-canvas-card').count()==3)
  check('Two ghost cards',canvas.locator('.bo-pain-canvas-ghost').count()==2)
  detail.get_by_role('textbox',name='Descrição (o que está acontecendo?)').fill('O valor total não é explicado antes de confirmar o pagamento.')
  detail.get_by_role('textbox',name='Causa raiz').fill('Ausência de cálculo de frete durante o checkout.')
  detail.get_by_role('textbox',name='Impacto').fill('Abandono e perda de confiança.')
  detail.get_by_role('textbox',name='Adicionar tag').fill('Frete')
  detail.get_by_role('textbox',name='Adicionar tag').press('Enter')
  check('Tag chip visible',detail.locator('.bo-entity-tag').filter(has_text='Frete').count()==1)
  canvas.get_by_role('button',name='Adicionar campo').click()
  canvas.get_by_role('button',name='Texto',exact=True).click()
  canvas.get_by_role('textbox',name='Texto',exact=True).fill('Observação personalizada')
  canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Sinal observável').click()
  canvas.get_by_role('textbox',name='Sinal observável',exact=True).fill('Taxa de abandono no checkout')
  card=canvas.locator('.bo-pain-canvas-card').filter(has=page.get_by_role('textbox',name='Sinal observável',exact=True))
  card.get_by_role('button',name='Opções de Sinal observável').click()
  card.get_by_role('button',name='Ocultar bloco (preserva conteúdo)').click()
  check('Ghost content preserved','Conteúdo preservado' in canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Sinal observável').inner_text())
  page.screenshot(path=str(OUT/'problem-canvas.png'),full_page=True)
  detail.locator('.bo-pain-back').click()
  expect(library).to_be_visible()
  library.locator('.bo-h76-problem-name').first.click()
  expect(detail).to_be_visible()
  check('Direct problem stays unvalidated after autosave',detail.get_by_text('PROBLEMA EM INVESTIGAÇÃO').count()>0)
  check('Cause persisted',detail.get_by_role('textbox',name='Causa raiz').input_value()=='Ausência de cálculo de frete durante o checkout.')
  check('Custom text persisted',canvas.get_by_role('textbox',name='Texto',exact=True).input_value()=='Observação personalizada')
  check('Tags persisted',detail.locator('.bo-entity-tag').filter(has_text='Frete').count()==1)
  canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Sinal observável').click()
  check('Hidden text recovered',canvas.get_by_role('textbox',name='Sinal observável',exact=True).input_value()=='Taxa de abandono no checkout')
  detail.locator('.bo-pain-detail-tabs').get_by_role('button',name='Validação',exact=False).click()
  check('Cannot validate without evidence',detail.get_by_role('button',name='Validar problema com evidências').is_disabled())
  detail.get_by_role('button',name='Excluir',exact=True).first.click()
  modal=page.get_by_role('alertdialog',name='Excluir problema');expect(modal).to_be_visible()
  modal.get_by_role('button',name='Cancelar').click()
  check('Cancel deletion preserves problem',detail.is_visible())
  (OUT/'results.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2),encoding='utf-8')
  browser.close()
finally:server.shutdown()
