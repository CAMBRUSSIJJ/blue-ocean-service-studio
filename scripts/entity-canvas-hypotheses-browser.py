#!/usr/bin/env python3
"""Interactive regression: hypothesis canvas, draft autosave, tags and validation controls."""
import functools,json,threading
from pathlib import Path
from http.server import SimpleHTTPRequestHandler,ThreadingHTTPServer
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'artifacts'/'entity-canvas-hypotheses';OUT.mkdir(parents=True,exist_ok=True)
assert (ROOT/'dist'/'index.html').exists(),'Build dist before browser check'
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(SimpleHTTPRequestHandler,directory=str(ROOT/'dist')))
threading.Thread(target=server.serve_forever,daemon=True).start()
checks=[]
def check(label,value):
 checks.append({'name':label,'ok':bool(value)})
 if not value: raise AssertionError(label)
 print('PASS '+label,flush=True)
try:
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True)
  page=browser.new_page(viewport={'width':1470,'height':920})
  page.goto(f'http://127.0.0.1:{server.server_port}',wait_until='domcontentloaded')
  page.get_by_role('button',name='Abrir workspace local sem conta').click()
  page.get_by_role('button',name='Novo projeto',exact=True).click()
  page.get_by_label('Nome do projeto',exact=True).fill('Hypothesis Canvas QA')
  page.get_by_label('Serviço principal',exact=True).fill('Compra online')
  page.get_by_role('button',name='Criar projeto',exact=True).click()
  page.locator('button[aria-label="Hipóteses"]').first.click()
  library=page.locator('[data-hypotheses-h75="library"]')
  expect(library).to_be_visible()
  library.locator('.bo-h71-toolbar').get_by_role('button',name='Criar Hipótese').click()
  form=page.locator('form.bo-h71-create-modal')
  form.locator('input').first.fill('Usuários não entendem o cálculo de frete')
  form.get_by_role('button',name='Criar e abrir').click()
  detail=page.locator('[data-hypotheses-h75="detail"]')
  expect(detail).to_be_visible()
  canvas=detail.locator('[data-entity-canvas="1"]')
  check('Three hypothesis blocks initially visible',canvas.locator('.bo-pain-canvas-card').count()==3)
  check('Two optional hypothesis ghost cards',canvas.locator('.bo-pain-canvas-ghost').count()==2)
  detail.get_by_role('textbox',name='Descrição (por que acreditamos?)',exact=True).fill('Entrevistas sugerem dúvida sobre o preço total.')
  detail.get_by_role('textbox',name='Premissa',exact=True).fill('O comprador espera previsão total')
  detail.get_by_role('textbox',name='Comportamento esperado',exact=True).fill('Com frete prévio, menos abandonos')
  detail.get_by_role('textbox',name='Adicionar tag').fill('Frete')
  detail.get_by_role('textbox',name='Adicionar tag').press('Enter')
  check('Tag chip displayed',detail.locator('.bo-entity-tag').filter(has_text='Frete').count()==1)
  canvas.get_by_role('button',name='Adicionar campo').click()
  canvas.get_by_role('button',name='Texto',exact=True).click()
  canvas.get_by_role('textbox',name='Texto',exact=True).fill('Nota individual que deve permanecer')
  canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Impacto se estiver errada').click()
  canvas.get_by_role('textbox',name='Impacto se estiver errada',exact=True).fill('Investimento em recurso irrelevante')
  card=canvas.locator('.bo-pain-canvas-card').filter(has=page.get_by_role('textbox',name='Impacto se estiver errada',exact=True))
  card.get_by_role('button',name='Opções de Impacto se estiver errada').click()
  card.get_by_role('button',name='Ocultar bloco (preserva conteúdo)').click()
  check('Ghost card indicates preserved contents','Conteúdo preservado' in canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Impacto se estiver errada').inner_text())
  page.screenshot(path=str(OUT/'hypotheses-canvas.png'),full_page=True)
  detail.locator('.bo-pain-back').click()
  expect(library).to_be_visible()
  library.locator('.bo-h75-name').first.click()
  expect(detail).to_be_visible()
  check('Premise persisted',detail.get_by_role('textbox',name='Premissa',exact=True).input_value()=='O comprador espera previsão total')
  check('Custom field persisted',canvas.get_by_role('textbox',name='Texto',exact=True).input_value()=='Nota individual que deve permanecer')
  check('Tags persisted',detail.locator('.bo-entity-tag').filter(has_text='Frete').count()==1)
  canvas.locator('.bo-pain-canvas-ghost').filter(has_text='Impacto se estiver errada').click()
  check('Hidden hypothesis content restored',canvas.get_by_role('textbox',name='Impacto se estiver errada',exact=True).input_value()=='Investimento em recurso irrelevante')
  detail.get_by_role('button',name='Validação',exact=True).click()
  expect(detail.get_by_role('button',name='Validar como Problema')).to_be_disabled()
  check('Validation remains blocked without graph evidence',True)
  detail.get_by_role('button',name='Excluir',exact=True).first.click()
  dialog=page.get_by_role('alertdialog',name='Excluir hipótese')
  expect(dialog).to_be_visible()
  dialog.get_by_role('button',name='Cancelar').click()
  check('Cancel preserves hypothesis',detail.is_visible())
  (OUT/'results.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2),encoding='utf-8')
  browser.close()
finally:server.shutdown()
