#!/usr/bin/env python3
"""End-to-end gate for Persona creation page and local saved filter views."""
import functools
import json
import re
import threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT=Path(__file__).resolve().parents[1]
assert (ROOT/'dist'/'index.html').exists(), 'Build dist before browser QA'
server=ThreadingHTTPServer(('127.0.0.1',0), functools.partial(SimpleHTTPRequestHandler,directory=str(ROOT/'dist')))
thread=threading.Thread(target=server.serve_forever,daemon=True);thread.start()
url=f'http://127.0.0.1:{server.server_port}'
checks=[]

def check(name,value):
    checks.append((name,bool(value)))
    if not value: raise AssertionError(name)
    print('PASS '+name,flush=True)

try:
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True)
        page=browser.new_page(viewport={'width':1450,'height':980}, accept_downloads=False)
        page.goto(url,wait_until='domcontentloaded')
        page.get_by_role('button',name='Abrir workspace local sem conta').click()
        page.get_by_role('button',name='Novo projeto',exact=True).click()
        page.get_by_label('Nome do projeto',exact=True).fill('Personas UX QA')
        page.get_by_label('Serviço principal',exact=True).fill('Atendimento')
        page.get_by_role('button',name='Criar projeto',exact=True).click()
        if not page.locator('button[aria-label="Personas"]').is_visible():
            page.locator('[data-sidebar-section="context"] .bo-h740h14-section-toggle').click()
        page.locator('button[aria-label="Personas"]').click()
        library=page.locator('[data-personas-h71="library"]')
        expect(library).to_be_visible()
        check('Default mode uses cards',library.get_attribute('data-persona-view')=='cards')
        library.get_by_role('button',name='Nova Persona').click()
        form=page.get_by_role('dialog',name='Criar Persona')
        expect(form).to_be_visible()
        form.get_by_role('button',name='Criar e editar').click()
        expect(form.get_by_role('alert')).to_contain_text('Informe um nome')
        check('Empty creation explains missing title without disabling its button',True)
        form.get_by_label('Quem é esta pessoa?').fill('Marcos, gerente de loja que precisa reduzir o tempo de atendimento')
        form.get_by_role('button',name='Criar e editar').click()
        detail=page.locator('[data-personas-h71="detail"]')
        expect(detail).to_be_visible()
        check('Quick input preserves Persona title',detail.get_by_role('textbox',name='Nome da Persona').input_value()=='Marcos')
        visual=detail.locator('[data-persona-visual-editor]')
        expect(visual).to_be_visible()
        check('Context supplied by the user becomes profile summary','gerente de loja' in visual.get_by_role('textbox',name='Resumo da Persona').input_value())
        check('Simple profile starts with the three essential cards',visual.locator('[data-persona-visual-card]').count()==3)
        check('Live preview shows Persona context', 'gerente de loja' in visual.locator('.bo-p6-live-profile').inner_text())
        visual.locator('[data-persona-visual-card="goal"]').get_by_role('textbox',name='Objetivo').fill('Diminuir o tempo do atendimento')
        check('Live preview updates while typing','Diminuir o tempo do atendimento' in visual.locator('.bo-p6-live-profile').inner_text())
        visual.get_by_role('button',name=re.compile('Adicionar bloco')).click()
        visual.locator('.bo-p5-library-grid').get_by_role('button',name=re.compile('Comportamentos')).click()
        check('Adding an advanced block activates advanced research',detail.get_by_role('button',name='Decisões',exact=True).count()==1)
        visual.locator('[data-persona-visual-card="behaviors"]').get_by_role('textbox',name='Comportamentos').fill('Pesquisa preços antes da contratação')
        detail.get_by_role('button',name='Personalizar interface').click()
        panel=page.locator('#bo-p2-persona-customize')
        expect(panel).to_be_visible()
        panel.get_by_role('button',name='Equilibrado').click()
        detail.get_by_role('button',name='Personalizar interface').click()
        goal=visual.locator('[data-persona-visual-card="goal"]')
        goal.get_by_label('Opções do bloco Objetivo principal').click()
        goal.get_by_role('button',name='Alterar largura').click()
        check('Goal card can become full width',goal.get_attribute('data-width')=='full')
        visual.get_by_role('button',name=re.compile('Adicionar bloco')).click()
        visual.locator('.bo-p5-library-grid').get_by_role('button',name=re.compile('Escala de preferência')).click()
        scale=visual.locator('[data-persona-visual-card="scale"]')
        expect(scale).to_be_visible()
        scale.get_by_role('slider',name='Posição da escala de preferência').fill('71')
        expect(detail.locator('.bo-h724-save-badge')).to_contain_text('Salvo neste dispositivo',timeout=8000)
        check('Autosave confirms local persistence without a manual footer',detail.get_by_role('button',name='Salvar alterações').count()==0)
        detail.get_by_role('button',name='Personas',exact=True).click()
        library=page.locator('[data-personas-h71="library"]')
        expect(library.locator('[data-persona-card]')).to_have_count(1)
        library.get_by_role('button',name='Abrir Persona').click()
        reopened_detail=page.locator('[data-personas-h71="detail"]')
        expect(reopened_detail).to_be_visible()
        check('Advanced research survives reopening',reopened_detail.get_by_role('button',name='Decisões',exact=True).count()==1)
        visual=reopened_detail.locator('[data-persona-visual-editor]')
        check('Card layout survives reopening',visual.locator('[data-persona-visual-card="goal"]').get_attribute('data-width')=='full')
        check('Scale preference survives reopening',visual.locator('[data-persona-visual-card="scale"]').get_by_role('slider').input_value()=='71')
        check('Observed behaviors survive save and reopen','Pesquisa preços antes da contratação' in visual.locator('[data-persona-visual-card="behaviors"]').inner_text()
              or 'Pesquisa preços antes da contratação' in visual.locator('[data-persona-visual-card="behaviors"]').get_by_role('textbox').input_value())
        page.locator('[data-personas-h71="detail"]').get_by_role('button',name='Personas',exact=True).click()
        library.get_by_role('button',name='Filtros de personas').click()
        filters=page.get_by_role('dialog',name='Filtrar Personas')
        expect(filters).to_be_visible()
        filters.get_by_role('button',name='Sem evidências').click()
        filters.get_by_role('button',name='Adicionar condição').click()
        filters.get_by_label('Campo da condição 1').select_option('evidence')
        filters.get_by_label('Operador da condição 1').select_option('equals')
        filters.get_by_label('Valor da condição 1').fill('0')
        filters.get_by_role('button',name='Aplicar filtros').click()
        check('Combined filters match the created Persona', library.locator('[data-persona-card]').count()==1)
        library.get_by_role('button',name='Visualizações',exact=False).click()
        library.get_by_label('Salvar visão atual').fill('Sem evidências QA')
        library.get_by_role('button',name='Salvar visualização').click()
        library.get_by_role('button',name='Tabela',exact=True).click()
        check('Switch to table renders only table',library.locator('[data-persona-table]').count()==1)
        library.get_by_role('button',name='Exibição',exact=False).click()
        library.get_by_role('checkbox',name='Atualizado').uncheck()
        check('Column configuration hides updated header',library.locator('th').filter(has_text='ATUALIZADO').count()==0)
        library.get_by_role('button',name='Concluir',exact=True).click()
        library.get_by_role('button',name='Visualizações',exact=False).click()
        library.get_by_role('button',name='Sem evidências QA',exact=True).click()
        check('Saved view restores cards and rule',library.get_attribute('data-persona-view')=='cards' and library.locator('[data-persona-card]').count()==1)
        page.reload(wait_until='domcontentloaded')
        if not page.locator('button[aria-label="Personas"]').is_visible():
            page.locator('[data-sidebar-section="context"] .bo-h740h14-section-toggle').click()
        page.locator('button[aria-label="Personas"]').click()
        page.get_by_role('button',name='Visualizações',exact=False).click()
        check('Saved view persists across reload',page.get_by_role('button',name='Sem evidências QA',exact=True).count()==1)
        browser.close()
finally:
    server.shutdown()
print(json.dumps({'passed':len(checks),'checks':[name for name,_ in checks]},ensure_ascii=False))
