import assert from 'node:assert/strict';
import { cardsInCell, moveJourneyCard } from '../src/domain/journey-card-operations.ts';
const a = {id:'a',type:'text',label:'Ações',cards:{one:'Legado'},cardItems:{two:[{id:'two-card',content:'Outra'}]}};
const b = {id:'b',type:'text',label:'Notas',cards:{}};
let lanes=[a,b];
lanes=moveJourneyCard(lanes,'a','one','legacy:a:one','b','two');
assert.deepEqual(cardsInCell(lanes[0],'one'),[]);
assert.equal(cardsInCell(lanes[1],'two')[0].content,'Legado');
assert.equal(cardsInCell(a,'one')[0].content,'Legado','immutable source');
lanes=moveJourneyCard(lanes,'a','two','two-card','b','two',0);
assert.deepEqual(cardsInCell(lanes[1],'two').map(c=>c.id),['two-card','legacy:a:one']);
lanes=moveJourneyCard(lanes,'b','two','legacy:a:one','b','two',0);
assert.deepEqual(cardsInCell(lanes[1],'two').map(c=>c.id),['legacy:a:one','two-card']);
const snapshot=JSON.parse(JSON.stringify(lanes));
assert.deepEqual(cardsInCell(snapshot[1],'two').map(c=>c.content),['Legado','Outra']);
assert.equal(moveJourneyCard(lanes,'a','one','missing','b','two'),lanes);
assert.equal(moveJourneyCard(lanes,'b','two','two-card','missing','one'),lanes);
assert.equal(moveJourneyCard(lanes,'b','two','two-card','b','two',1).length,2);
assert.equal(a.cards.one,'Legado');
console.log('PASS: H17.0.9 movement between lanes/stages, ordering, legacy, immutability and JSON roundtrip');
