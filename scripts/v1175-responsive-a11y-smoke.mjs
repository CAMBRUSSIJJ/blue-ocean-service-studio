import { existsSync, readFileSync } from 'node:fs';
const pkg=JSON.parse(readFileSync('package.json','utf8'));
const app=readFileSync('src/App.tsx','utf8');
const main=readFileSync('src/main.tsx','utf8');
const css=readFileSync('src/runtime/responsive-accessibility.css','utf8');
const js=readFileSync('src/runtime/responsive-accessibility.js','utf8');
const wb=readFileSync('src/runtime/whiteboard-core.js','utf8');
const toast=readFileSync('src/components/Toast.tsx','utf8');
const tokens=readFileSync('src/design-system/tokens.css','utf8');
const index=readFileSync('index.html','utf8');
const checks=[];const check=(label,ok)=>{checks.push({label,ok});console.log(`${ok?'OK  ':'FAIL'} ${label}`)};
const [maj,min,patch]=pkg.version.split('.').map(Number);
check('versão é V1.17.5 ou superior',maj>1||(maj===1&&(min>17||(min===17&&patch>=5))));
check('assets responsivos existem',existsSync('src/runtime/responsive-accessibility.css')&&existsSync('src/runtime/responsive-accessibility.js'));
check('pipeline publica CSS/JS responsivos',index.includes('/v1175-responsive-a11y.css')&&index.includes('/v1175-responsive-a11y.js'));
check('body ativa bo-v1175',main.includes("'bo-v1175'"));
check('skip link para conteúdo existe',app.includes('bo1175-skip-link')&&app.includes('#bo-main-content'));
check('navegação mobile tem drawer e bottom nav',app.includes('bo1175-mobile-menu')&&app.includes('bo1175-mobile-scrim')&&app.includes('bo1175-mobile-nav'));
check('breakpoints explícitos cobrem desktop/tablet/mobile',css.includes('@media(min-width:1280px)')&&css.includes('min-width:768px')&&css.includes('max-width:599px'));
check('tablet usa alvo de toque >=40px',css.includes('--bo-touch-target:40px')&&/min-height:40px/.test(css));
check('mobile usa alvo de toque 44px',css.includes('--bo-touch-target:44px')&&/min-height:44px/.test(css));
check('foco visível é global e semântico',css.includes(':focus-visible')&&css.includes('--bo-a11y-focus'));
check('prefers-reduced-motion está coberto',css.includes('@media(prefers-reduced-motion:reduce)'));
check('prefers-contrast está coberto',css.includes('@media(prefers-contrast:more)'));
check('texto faint foi elevado para contraste AA',tokens.includes('--bo-color-text-faint:#667085;'));
check('toast é anunciado por leitor de tela',toast.includes('role="status"')&&toast.includes('aria-live="polite"'));
check('quadro reconhece modo mobile read-only',wb.includes("function mobileReadOnly()")&&wb.includes("bo1175-mobile-read"));
check('edição por arraste é bloqueada no mobile',wb.includes("if(mobileReadOnly()){e.stopPropagation();selected=[id]")&&wb.includes("quadro está em modo leitura"));
check('toolbar mobile remove ferramentas de criação',wb.includes("['Selecionar','Mão','Buscar'].includes(entry.label)"));
check('mobile mantém comentários como ação primária',wb.includes("bo1175-mobile-comment")&&wb.includes("show?.('comments')"));
check('inspector mobile fica em leitura',js.includes('data-bo1175-mobile-disabled')&&css.includes('.bo1174-board.bo1175-mobile-read .rt144-inspector'));
const failed=checks.filter(x=>!x.ok).length;console.log(`\nV1.17.5 Responsive & Accessibility: ${checks.length-failed}/${checks.length}`);if(failed)process.exit(1);
