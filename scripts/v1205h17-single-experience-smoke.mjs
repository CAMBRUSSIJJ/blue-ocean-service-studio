import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const exists=(p)=>fs.existsSync(p);
const app=read('src/App.tsx');
const workspace=read('src/views/BlueprintWorkspaceView.tsx');
const research=read('src/views/ResearchStudioView.tsx');
const service=read('src/services/experience-profile.ts');
const css=read('src/runtime/single-experience-h17.css');
const style=read('src/style.css');
const main=read('src/main.tsx');
const pkg=JSON.parse(read('package.json'));
const launcher=read('start-linux.sh');
const preflight=read('preflight-linux.sh');
const changelog=read('CHANGELOG.md');
let ok=0,fail=0;
const check=(label,pass)=>{console.log(`${pass?'OK':'FAIL'} ${label}`);pass?ok++:fail++;};
check('CSS H17 existe', exists('src/runtime/single-experience-h17.css'));
check('Perfil ativo único é advanced', service.includes("ACTIVE_EXPERIENCE_LEVEL: ExperienceLevel = 'advanced'"));
check('Leitura ignora preferência antiga', service.includes('return ACTIVE_EXPERIENCE_LEVEL'));
check('Escrita normaliza para advanced', service.includes('localStorage.setItem(EXPERIENCE_PROFILE_STORAGE_KEY, ACTIVE_EXPERIENCE_LEVEL)'));
check('Hook publica perfil canônico', service.includes('meta: EXPERIENCE_LEVELS[ACTIVE_EXPERIENCE_LEVEL]'));
check('App não importa lista de níveis', !app.includes('EXPERIENCE_LEVELS, useExperienceProfile'));
check('App não possui seletor de modo', !app.includes('MODO DE ORIENTAÇÃO') && !app.includes('Como você prefere trabalhar?'));
check('App não renderiza experienceControl', !app.includes('{experienceControl}'));
check('App publica H17', app.includes('data-single-experience="H17"'));
check('App preserva projeção avançada via perfil', app.includes('data-experience-level={experience.level}'));
check('Workspace publica H17', workspace.includes('data-single-experience="H17"'));
check('Workspace não mostra chip Modo', !workspace.includes('Modo · {experience.meta.label}'));
check('Research publica H17', research.includes('data-single-experience="H17"'));
check('Capacidades avançadas continuam completas', service.includes("if (level === 'advanced') return true;"));
check('Pesquisa avançada mantém rastreabilidade', service.includes("if (level === 'advanced') return true;") && research.includes('traceabilityScore'));
check('CSS H17 esconde affordances legadas', css.includes('.bo-h16-experience-control') && css.includes('.bo-h16-profile-chip'));
check('style importa H17 após H16.8', style.indexOf('single-experience-h17.css') > style.indexOf('design-start-choice-h168.css'));
check('Host registra bo-h17', main.includes("'bo-h17'"));
check('metadata inicia em H17', String(pkg.description||'').includes('V1.20.5-H17 Single Experience Baseline'));
check('package registra smoke H17', Boolean(pkg.scripts?.['v1205h17:single-experience-smoke']));
check('QA inclui H17', String(pkg.scripts?.qa||'').includes('v1205h17:single-experience-smoke'));
check('launcher é H17', launcher.includes('RELEASE="H17.0.3.1"') || (launcher.includes('RELEASE="H17.0.5"') || launcher.includes('RELEASE="H17.0.4"')) || launcher.includes('RELEASE="H17.0.3"') || launcher.includes('RELEASE="H17.0.2"') || launcher.includes('RELEASE="H17.0.1"') || launcher.includes('RELEASE="H17"'));
check('preflight inclui H17', preflight.includes('v1205h17-single-experience-smoke.mjs'));
check('changelog inicia H17', changelog.includes('# V1.20.5-H17 — Single Experience Baseline'));
check('release notes H17 existem', exists('docs/archive/releases/RELEASE_NOTES_V1.20.5-H17.md'));
console.log(`\nV1.20.5-H17 Single Experience Baseline: ${ok}/${ok+fail} PASS`);
process.exit(fail?1:0);
