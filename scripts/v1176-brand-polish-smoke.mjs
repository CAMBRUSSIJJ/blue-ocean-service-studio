import { existsSync, readFileSync } from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const pkg=JSON.parse(read('package.json'));
const css=read('src/runtime/brand-polish.css');
const js=read('src/runtime/brand-polish.js');
const prep=read('scripts/prepare-assets.mjs');
const index=read('index.html');
const main=read('src/main.tsx');
const app=read('src/App.tsx');
const boundary=read('src/components/AppErrorBoundary.tsx');
const home=read('src/views/WorkspaceHome.tsx');
const action=read('src/views/ActionPlanView.tsx');
const checks=[];const check=(label,ok)=>{checks.push({label,ok});console.log(`${ok?'OK  ':'FAIL'} ${label}`)};
const [maj,min,patch]=pkg.version.split('.').map(Number);
check('versão é V1.17.6 ou superior',maj>1||(maj===1&&(min>17||(min===17&&patch>=6))));
check('assets finais de polish existem',existsSync('src/runtime/brand-polish.css')&&existsSync('src/runtime/brand-polish.js'));
check('ilustração SVG própria de estado vazio existe',existsSync('src/brand/blue-ocean-empty-state.svg'));
check('pipeline publica brand polish e empty-state',prep.includes('v1176-brand-polish.css')&&prep.includes('v1176-brand-polish.js')&&prep.includes('blue-ocean-empty-state.svg'));
check('index carrega polish por último no CSS',index.indexOf('/v1176-brand-polish.css')>index.indexOf('/v1175-responsive-a11y.css'));
check('index carrega runtime de polish',index.includes('/v1176-brand-polish.js'));
check('body ativa bo-v1176',main.includes("'bo-v1176'"));
check('marca final usa blue-ocean-mark',css.includes("url('/blue-ocean-mark.svg')"));
check('estado vazio usa SVG BLUE OCEAN',css.includes("url('/blue-ocean-empty-state.svg')"));
check('motion usa 120–200 ms',css.includes('--bo1176-motion-fast:120ms')&&css.includes('--bo1176-motion-normal:180ms')&&css.includes('--bo1176-motion-slow:200ms'));
check('reduced motion permanece respeitado',css.includes('@media(prefers-reduced-motion:reduce)'));
check('loading branded inclui mark e skeleton',js.includes('bo1176-state-mark')&&js.includes('bo1176-boot-lines')&&css.includes('bo1176-shimmer'));
check('offline recebe microcopy e aria-live',js.includes("aria-live','polite")&&js.includes('Você está offline. O trabalho local continua disponível'));
check('fatal state preserva dados e usa ações padronizadas',boundary.includes('Seus dados locais foram preservados')&&boundary.includes('bo1176-error-actions'));
check('404 branded existe',existsSync('public/404.html')&&read('public/404.html').includes('BLUE OCEAN · 404'));
check('sidebar não volta a texto abaixo de 11 px no polish',!/[{;]\s*font-size:\s*(?:[0-9]|10(?:\.\d+)?)px/.test(css));
check('microcopy principal não usa jornada(s) ou quadro(s)',!app.includes('jornada(s)')&&!app.includes('quadro(s)'));
check('Plano de Ação usa grupo MELHORAR',action.includes('MELHORAR')&&!action.includes('>EXECUTAR<'));
check('Home mantém empty states úteis',(home.includes('Comece criando seu primeiro mapa')||home.includes('Crie seu primeiro serviço'))&&home.includes('Você ainda não adicionou nenhum favorito.')&&(home.includes('Nenhum alerta prioritário agora.')||home.includes('Seu serviço ainda está vazio')));
check('QA principal inclui polish final',pkg.scripts.qa.includes('brand:polish:smoke'));
const failed=checks.filter(x=>!x.ok).length;console.log(`\nV1.17.6 Brand & Product Polish Final: ${checks.length-failed}/${checks.length}`);if(failed)process.exit(1);
