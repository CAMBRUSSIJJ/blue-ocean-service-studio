import assert from 'node:assert/strict';
import { cardsInCell, addCellCard, editCellCard, removeCellCard, setCellCards } from '../src/domain/journey-card-operations.ts';
const old = { id: 'lane', type: 'text', label: 'Notas', cards: { discovery: 'Observação antiga', purchase: 'Preservar' } };
assert.deepEqual(cardsInCell(old, 'discovery').map(c => c.content), ['Observação antiga']);
assert.deepEqual(cardsInCell(old, 'missing'), []);
let lane = addCellCard(old, 'discovery', 'card-2');
assert.equal(cardsInCell(lane, 'discovery').length, 2);
assert.equal(cardsInCell(old, 'discovery').length, 1, 'original must not mutate');
lane = editCellCard(lane, 'discovery', 'card-2', 'Segunda observação');
assert.deepEqual(cardsInCell(lane, 'discovery').map(c=>c.content), ['Observação antiga','Segunda observação']);
assert.equal(lane.cards.purchase,'Preservar');
lane = removeCellCard(lane, 'discovery', `legacy:lane:discovery`);
assert.deepEqual(cardsInCell(lane, 'discovery').map(c=>c.content), ['Segunda observação']);
lane = removeCellCard(lane, 'discovery', 'card-2');
assert.deepEqual(cardsInCell(lane, 'discovery'), []);
assert.equal(lane.cards.discovery, '');
assert.deepEqual(cardsInCell(lane, 'purchase').map(c=>c.content), ['Preservar']);
const restored = structuredClone(lane);
assert.deepEqual(cardsInCell(restored, 'discovery'), [], 'empty cell survives serialization');
assert.deepEqual(cardsInCell(setCellCards(old,'discovery',[]),'discovery'), []);
console.log('PASS: H17.0.9 - legacy, multi-card CRUD, immutability, isolation and JSON persistence');
