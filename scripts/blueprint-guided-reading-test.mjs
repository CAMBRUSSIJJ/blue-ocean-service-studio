import assert from 'node:assert/strict';
import { buildBlueprintGuidedReading, blueprintEmotionValue } from '../src/services/blueprint-guided-reading.js';
assert.equal(blueprintEmotionValue({ emotion: 'negative' }), -1);
assert.equal(blueprintEmotionValue({ emotion: 'positive', emotionScore: -2 }), -2);
assert.equal(blueprintEmotionValue({ emotion: 'neutral', emotionScore: '2' }), 0);
const stages=[{id:'a',title:'Início',emotion:'negative'}, {id:'b',title:'Fim',emotion:'positive',emotionScore:2}];
const lanes=[{key:'customer',label:'Cliente'}, {key:'backstage',label:'Bastidores'}];
const rows=[{complete:1,missing:[{key:'backstage'}]},{complete:2,missing:[]}];
const issues=[{stageId:'a',severity:'warning',message:'Mensagem'},{stageId:'a',severity:'critical',message:'Falha'},{stageId:'outside',severity:'critical',message:'Fora da Jornada'}];
const before=JSON.stringify({stages,lanes,rows,issues});
const result=buildBlueprintGuidedReading({stages,lanes,rows,issues,qualityDimensions:[{key:'empathy',label:'Empatia'}],qualityCriteria:{empathy:{criterion:'Revisão humana'}}});
assert.equal(result.coverage,75);
assert.deepEqual(result.checklist.map(x=>x.covered),[2,1]);
assert.equal(result.next.key,'backstage');
assert.equal(result.priorities.length,2);
assert.equal(result.priorities[0].message,'Falha');
assert.equal(result.qualityConfigured,1);
assert.deepEqual(result.emotion.map(x=>x.value),[-1,2]);
assert.equal(JSON.stringify({stages,lanes,rows,issues}),before,'Guide must not mutate canonical input');
assert.equal(buildBlueprintGuidedReading().coverage,0);
console.log('Blueprint guided reading: OK');
